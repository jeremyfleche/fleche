#include "slider.h"
#include <array>
#include <cstdio>
#include <random>
#include <vector>

std::mt19937_64 rng(42);

Bitboard random_sparse() { return rng() & rng() & rng(); }

Bitboard find_magic_number(std::array<Bitboard, 64> const& mask_table, Bitboard (*attack_function)(int, Bitboard),
                           int square) {
	Bitboard mask = mask_table[square];
	int n = __builtin_popcountll(mask);
	int size = 1 << n;
	Bitboard magic = 0;

	std::vector<Bitboard> configs(size);
	std::vector<Bitboard> attacks(size);

	Bitboard sub = 0;
	for (int i = 0; i < size; ++i) {
		configs[i] = sub;
		attacks[i] = attack_function(square, sub);
		sub = (sub - mask) & mask; // generate next subset of mask
	}

	bool found = false;
	while (!found) {
		magic = random_sparse();
		if (__builtin_popcountll((mask * magic) >> 56) < 6)
			continue; // not enough bits set

		std::vector<Bitboard> used(size, 0);
		found = true;
		for (int i = 0; i < size; ++i) {
			int index = (configs[i] * magic) >> (64 - n);
			if (used[index] == 0) {
				used[index] = attacks[i];
			} else if (used[index] != attacks[i]) {
				found = false;
				break;
			}
		}
	}

	return magic;
}

static void print_magics(const char* name, const std::array<Bitboard, 64>& magics) {
	std::printf("inline constexpr std::array<Bitboard, 64> %s = {\n", name);
	for (int sq = 0; sq < 64; ++sq) {
		if (sq % 4 == 0)
			std::printf("\t");
		std::printf("0x%016llxULL,", static_cast<unsigned long long>(magics[sq]));
		std::printf(sq % 4 == 3 ? "\n" : " ");
	}
	std::printf("};\n");
}

int main() {
	std::array<Bitboard, 64> rook_magics{};
	std::array<Bitboard, 64> bishop_magics{};

	for (int sq = 0; sq < 64; ++sq)
		rook_magics[sq] = find_magic_number(ROOK_MASK, slow_rook_attacks, sq);
	for (int sq = 0; sq < 64; ++sq)
		bishop_magics[sq] = find_magic_number(BISHOP_MASK, slow_bishop_attacks, sq);

	std::printf("// Generated by tools/find_magics.cpp (seed 42).\n");
	std::printf("// Do not edit by hand: run \"make magics\" to regenerate.\n");
	std::printf("#pragma once\n\n");
	std::printf("#include \"types.h\"\n");
	std::printf("#include <array>\n\n");
	std::printf("// clang-format off\n");
	print_magics("ROOK_MAGIC_NUMBERS", rook_magics);
	std::printf("\n");
	print_magics("BISHOP_MAGIC_NUMBERS", bishop_magics);
	std::printf("// clang-format on\n");
	return 0;
}